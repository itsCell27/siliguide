package com.example.siliguide.data.repository

import app.cash.sqldelight.coroutines.asFlow
import app.cash.sqldelight.coroutines.mapToList
import com.example.siliguide.data.local.sqldelight.SiliGuideDatabaseManager
import com.example.siliguide.data.local.mapper.toDomainModel
import com.example.siliguide.domain.model.Plant
import com.example.siliguide.domain.repository.PlantRepository
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import javax.inject.Inject

class PlantRepositoryImpl @Inject constructor(
    private val dbManager: SiliGuideDatabaseManager
) : PlantRepository {

    private val queries = dbManager.queries

    override fun getPlantsByUser(userId: String): Flow<List<Plant>> {
        // Scoped to target account profile index with performance optimizations
        return queries.getPlantsByUser(userId)
            .asFlow()
            .mapToList(Dispatchers.IO)
            .map { sqlEntities ->
                sqlEntities.map { it.toDomainModel() }
            }
    }

    override suspend fun insertPlant(plant: Plant) {
        // Enforces all 7 required arguments generated by our Upsert declaration
        queries.insertPlant(
            plant_id = plant.plantId,
            user_id = plant.userId,
            plant_name = plant.name,
            date_created = plant.dateCreated,
            updated_at = plant.updatedAt,
            last_analyzed_at = plant.lastAnalyzedAt,
            device_id = plant.deviceId
        )
    }

    override suspend fun markPlantAsDeletedById(updatedAt: Long, plantId: String) {
        queries.markPlantDeleted(updatedAt, plantId)
    }

    override suspend fun deletePlant(plantId: String) {
        queries.deletePlant(plantId)
    }

    override suspend fun getPlantById(plantId: String): Plant? {
        return queries.getPlantById(plantId)
            .executeAsOneOrNull()
            ?.toDomainModel()
    }

    override suspend fun updatePlantName(plantId: String, updatedAt: Long, name: String) {
        // Invokes our new targeted update syntax cleanly
        queries.updatePlantName(plant_name = name, updated_at = updatedAt, plant_id = plantId)
    }

    override suspend fun linkDevice(deviceId: String, updatedAt: Long, plantId: String) {
        queries.linkPlantDevice(device_id = deviceId, updated_at = updatedAt, plant_id = plantId)
    }

    override suspend fun getLinkedPlantsByDeviceId(deviceId: String): Plant {
        return queries.getLinkedPlantByDeviceId(deviceId)
            .executeAsOne()
            .toDomainModel()
    }

    override suspend fun unlinkDevice(updatedAt: Long, plantId: String) {
        queries.unlinkPlantDevice(updatedAt, plantId)
    }

    override suspend fun getPlantByDeviceId(deviceId: String): List<Plant> {
        return queries.getPlantByDeviceId(deviceId)
            .executeAsList()
            .map { it.toDomainModel() }
    }
}