package com.example.siliguide.data.local.mapper

import com.example.siliguide.domain.model.Plant
import com.example.siliguide.data.local.Plants // This is the class generated by SQLDelight!

// 1. Convert SQL Database row -> Pure Domain Kotlin Object
fun Plants.toDomainModel(): Plant {
    return Plant(
        plantId = this.plant_id,
        userId = this.user_id,
        name = this.plant_name,
        dateCreated = this.date_created,
        lastAnalyzedAt = this.last_analyzed_at,
        isSynced = this.is_synced == 1L, // SQLite uses 1 for true, 0 for false
        deviceId = this.device_id
    )
}

// 2. Helper to convert Domain Boolean -> SQL Integer
fun Plant.toSyncInt(): Long {
    return if (this.isSynced) 1L else 0L
}